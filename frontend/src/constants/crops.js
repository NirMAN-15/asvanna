export const getCropById = (id) => {
  return MASTER_CROPS.find(c => c.id === Number(id)) || MASTER_CROPS[0];
};

export const getCropByCode = (code) => {
  if (!code) return MASTER_CROPS[0];
  const upper = String(code).toUpperCase().trim();
  return MASTER_CROPS.find(c => c.code === upper || c.crop_code === upper) || MASTER_CROPS[0];
};

export const getCropImage = (cropIdOrCode) => {
  if (!cropIdOrCode) return MASTER_CROPS[0].image;
  const match = MASTER_CROPS.find(
    c => c.id === Number(cropIdOrCode) || c.code === String(cropIdOrCode).toUpperCase()
  );
  return match?.image || MASTER_CROPS[0].image;
};
